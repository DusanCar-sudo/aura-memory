#!/usr/bin/env node
// Two-way bridge between the shared markdown memory store and the other agents' formats.
// Usage: node aura-bridge.mjs <hubMemoryDir> <auraMemoryDir> [agentsMdPath]
import fs from 'node:fs';
import path from 'node:path';

const memDir = process.argv[2];
const auraDir = process.argv[3];
const agentsMd = process.argv[4] || '';
if (!memDir || !auraDir) {
  console.error('usage: aura-bridge.mjs <hubMemoryDir> <auraMemoryDir> [agentsMdPath]');
  process.exit(2);
}
fs.mkdirSync(auraDir, { recursive: true });
const auraFile = path.join(auraDir, 'default.json');
const NL = /\r?\n/;

const slug = (s) => s.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const key = (s) => slug(s).replace(/-/g, '_');

function parse(file) {
  const raw = fs.readFileSync(file, 'utf8');
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  const fm = m ? m[1] : '';
  const body = (m ? raw.slice(m[0].length) : raw).trim();
  const get = (k) => (fm.match(new RegExp('^\\s*' + k + ':\\s*(.+)$', 'm')) || [, ''])[1].trim();
  const name = get('name') || path.basename(file, '.md');
  return { name, description: get('description'), type: get('type') || 'project', body };
}

const mdFiles = () => fs.readdirSync(memDir).filter((f) => f.endsWith('.md') && f !== 'MEMORY.md');

// ---- markdown -> aura ----
const files = mdFiles();
const out = {};
const fromMd = new Set();
for (const f of files) {
  const p = path.join(memDir, f);
  const { name, description, body } = parse(p);
  const k = key(name);
  fromMd.add(k);
  out[k] = {
    value: (description ? description + '\n\n' : '') + body,
    updated: fs.statSync(p).mtime.toISOString(),
    source: 'shared-memory/' + f,
  };
}

// ---- aura -> markdown (anything Aura learned that the shared store does not have) ----
let prev = {};
try { prev = JSON.parse(fs.readFileSync(auraFile, 'utf8')); } catch { /* first run */ }
const created = [];
for (const [k, v] of Object.entries(prev)) {
  if (fromMd.has(k)) continue;
  if (v && v.source && String(v.source).startsWith('shared-memory/')) continue; // deleted upstream on purpose
  const name = k.replace(/_/g, '-');
  const file = path.join(memDir, name + '.md');
  if (fs.existsSync(file)) continue;
  const text = typeof v === 'string' ? v : (v && v.value) || '';
  if (!text.trim()) continue;
  const first = text.trim().split(NL)[0].slice(0, 160);
  fs.writeFileSync(
    file,
    ['---', 'name: ' + name, 'description: ' + first, 'metadata:', '  type: project', '---', '', text.trim(), ''].join('\n'),
    'utf8'
  );
  created.push(name);
  out[k] = { value: text, updated: (v && v.updated) || new Date().toISOString(), source: 'shared-memory/' + name + '.md' };
}

fs.writeFileSync(auraFile, JSON.stringify(out, null, 2), 'utf8');

// ---- keep MEMORY.md index complete, deduped and free of dead links ----
const idxPath = path.join(memDir, 'MEMORY.md');
let idx = fs.existsSync(idxPath) ? fs.readFileSync(idxPath, 'utf8') : '';
{
  const seen = new Set();
  const keep = [];
  for (const line of idx.split(NL)) {
    const m = line.match(/^- \[.*?\]\((.+?\.md)\)/);
    if (m) {
      if (seen.has(m[1])) continue;                                  // union merge duplicate
      if (!fs.existsSync(path.join(memDir, m[1]))) continue;         // memory was deleted
      seen.add(m[1]);
    } else if (line.trim() === '' && keep.length && keep[keep.length - 1].trim() === '') {
      continue;
    }
    keep.push(line);
  }
  idx = keep.join('\n').replace(/\n{3,}/g, '\n\n');
}
let added = 0;
for (const f of mdFiles()) {
  if (idx.includes('(' + f + ')')) continue;
  const { name, description } = parse(path.join(memDir, f));
  const title = name.replace(/[-_]/g, ' ').replace(/^./, (c) => c.toUpperCase());
  idx = idx.replace(/\s*$/, '\n') + '- [' + title + '](' + f + ') — ' + (description || 'see file') + '\n';
  added++;
}
fs.writeFileSync(idxPath, idx.replace(/\s*$/, '\n'), 'utf8');

// ---- markdown -> Codex (global AGENTS.md instructions) ----
if (agentsMd) {
  const dir = memDir.replace(/\\/g, '/');
  const tick = '`';
  const fence = '```';
  const doc = [
    '<!-- GENERATED by memsync. Do not edit by hand; edit the .md files in ' + dir + ' instead. -->',
    '# Shared memory',
    '',
    'Dusan runs three agents — Claude Code, Aura and Codex — against ONE shared memory store.',
    'It lives at ' + tick + dir + tick + ', a git repo synced between his Linux (Aura OS) and Windows installs.',
    '',
    '**Read it.** Before answering anything about Dusan, his machines or his projects, open the',
    'relevant file(s) from the index below. The index is a summary; the files hold the detail.',
    '',
    '**Write to it.** When you learn something durable (a preference, a project fact, a fix that took',
    'real work), create or update a file in that directory in this shape:',
    '',
    fence + 'markdown',
    '---',
    'name: <short-kebab-case-slug>',
    'description: <one line — this is what the other agents see in the index>',
    'metadata:',
    '  type: user | feedback | project | reference',
    '---',
    '',
    '<the fact. Link related memories with [[their-slug]].>',
    fence,
    '',
    'Then add one line to ' + tick + 'MEMORY.md' + tick + ': ' + tick + '- [Title](file.md) — hook' + tick + '.',
    'Do not keep durable facts only in your own private memory — the other two agents cannot see it.',
    'Afterwards run ' + tick + 'memsync' + tick + ' so the other machine gets it.',
    '',
    '## Index',
    '',
    fs.readFileSync(idxPath, 'utf8').trim(),
    '',
  ].join('\n');
  fs.mkdirSync(path.dirname(agentsMd), { recursive: true });
  fs.writeFileSync(agentsMd, doc, 'utf8');
}

console.log(
  'aura-bridge: ' + files.length + ' md -> aura, ' + created.length + ' new md from aura, ' +
  added + ' index lines added' + (agentsMd ? ', AGENTS.md written' : '')
);
